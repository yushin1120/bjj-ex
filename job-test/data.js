// 점수 계산 엔진
function calculateResultPersona(scores) {
  const sortedTraits = Object.keys(scores).sort((a, b) => scores[b] - scores[a]);
  const top1 = sortedTraits[0];
  const top2 = sortedTraits[1];
  const top3 = sortedTraits[2];

  // 가능한 3자리 조합 찾기
  const candidate1 = `${top1}${top2}${top3}`;
  const candidate2 = `${top1}${top3}${top2}`;
  const candidate3 = `${top2}${top1}${top3}`;

  if (JOB_PERSONAS[candidate1]) return { persona: JOB_PERSONAS[candidate1], topTraits: sortedTraits };
  if (JOB_PERSONAS[candidate2]) return { persona: JOB_PERSONAS[candidate2], topTraits: sortedTraits };
  if (JOB_PERSONAS[candidate3]) return { persona: JOB_PERSONAS[candidate3], topTraits: sortedTraits };

  // 상위 2글자 기반 탐색
  const twoLetterMatches = Object.keys(JOB_PERSONAS).filter(key => key.startsWith(`${top1}${top2}`) || (key.includes(top1) && key.includes(top2)));
  if (twoLetterMatches.length > 0) {
    return { persona: JOB_PERSONAS[twoLetterMatches[0]], topTraits: sortedTraits };
  }

  // 기본 fallback
  const firstLetterMatches = Object.keys(JOB_PERSONAS).filter(key => key.startsWith(top1));
  if (firstLetterMatches.length > 0) {
    return { persona: JOB_PERSONAS[firstLetterMatches[0]], topTraits: sortedTraits };
  }

  return { persona: JOB_PERSONAS["RIE"], topTraits: sortedTraits };
}
